import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(process.env.TEST_URL || 'http://localhost:3000');
  await page.waitForSelector('.welcome-banner');
  await page.waitForTimeout(800);
  await page.screenshot({ path: '/tmp/teachhelper-desktop.png', fullPage: true });
  assert.equal(await page.locator('.stat-card').count(), 4);
  await page.locator('.lesson-open').first().click();
  await page.waitForSelector('.att-row-2col');
  assert.equal(await page.locator('.att-row-2col').count(), 24);
  const row = page.locator('.att-row-2col').first();
  const before = await row.innerText();
  const size = await row.boundingBox();
  await row.click({ position: { x: size.width - 10, y: size.height / 2 } });
  await page.waitForTimeout(600);
  assert.notEqual(await page.locator('.att-row-2col').first().innerText(), before);
  await page.locator('.side-link[href="#groups"]').click();
  await page.waitForSelector('.group-page-grid');
  await page.locator('.page-heading .primary-button').click();
  await page.locator('#group-name').fill('ТЕСТ-99');
  await page.locator('.popup .btn-primary').click();
  await page.waitForTimeout(600);
  assert.equal(await page.locator('.group-card').count(), 7);
  await page.locator('.side-link[href="#exports"]').click();
  await page.waitForSelector('#export-subject');
  const downloaded = page.waitForEvent('download');
  await page.locator('.export-panel .primary-button').click();
  const download = await downloaded;
  assert.match(download.suggestedFilename(), /\.xlsx$/);
  assert.equal(await download.failure(), null);
  await page.locator('.side-link[href="#catalog"]').click();
  await page.waitForSelector('.catalog-grid');
  await page.locator('.subject-name').first().click();
  await page.waitForSelector('table');
  assert.equal(await page.locator('h1').innerText(), 'Основы программирования');
  assert.deepEqual(errors, []);
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, deviceScaleFactor: 1 });
  await mobile.goto(process.env.TEST_URL || 'http://localhost:3000');
  await mobile.waitForSelector('.welcome-banner');
  await mobile.waitForTimeout(300);
  await mobile.screenshot({ path: '/tmp/teachhelper-mobile.png', fullPage: true });
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth), 390);
  await mobile.locator('.mobile-toggle').click();
  assert.ok(await mobile.locator('body').evaluate(el => el.classList.contains('menu-open')));
  await mobile.locator('.side-link[href="#schedule"]').click();
  await mobile.waitForFunction(() => document.querySelector('h1')?.textContent === 'Расписание');
  assert.equal(await mobile.locator('h1').innerText(), 'Расписание');
  console.log('PASS: dashboard, grade cycle, group creation, Excel export, gradebook, responsive layout, mobile navigation.');
} finally { await browser.close(); }
